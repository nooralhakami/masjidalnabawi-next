"""Build data/library/hadith.json from HadeethEnc.com (Islam House / Rawad Translation Center).

Their terms (hadeethenc.com → «الشروط والسياسات») allow downloading and republishing the
translations provided: no change, addition or deletion; the publisher and source (HadeethEnc.com)
named clearly; the version of the translation stated; the translation's own details kept; no
unsuitable advertising. So every text is stored exactly as the API returns it, with its source,
the date it was fetched (the version), and the languages the encyclopedia really has for it.
A language it does not have gets no entry: the app then shows the Arabic with a notice.

Every record is `review: "draft"` until a qualified reviewer approves it (docs/PLAN-ISLAMIC-LIBRARY.md).

    python3 scripts/library-hadith-from-hadeethenc.py
"""
import json, sys, time, urllib.error, urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import date

API = 'https://hadeethenc.com/api/v1/hadeeths/one/?language={lang}&id={id}'
# The app's 26 languages.
LANGS = ['ar', 'en', 'tr', 'ur', 'id', 'uz', 'bn', 'fr', 'fa', 'ru', 'ms', 'ha', 'ml', 'sw', 'ps', 'so', 'ta', 'hi', 'bs', 'de', 'zh', 'am', 'ku', 'az', 'th', 'es']
# The encyclopedia's own codes where they differ from the app's.
CODE = {'ms': 'ms', 'ku': 'ku'}
# Pilot batch (owner, 2026-10-14): about the Prophet's Mosque and Madinah, and the virtues of the ten.
IDS = [
    ('mosque', '65090', 'فضل الصلاة في المسجد النبوي'),
    ('mosque', '65408', 'الروضة الشريفة بين البيت والمنبر'),
    ('mosque', '65407', 'المسجد الذي أُسِّس على التقوى'),
    ('mosque', '65406', 'بناء المسجد في عهد النبي ﷺ'),
    ('madinah', '65685', 'حرم المدينة'),
    ('madinah', '65691', 'طابة وجبل أحد'),
    ('companions', '65697', 'أبو بكر ثم عمر ثم عثمان'),
    ('companions', '11161', 'أبو بكر وعمر سيدا كهول أهل الجنة'),
    ('companions', '11190', 'أبو عبيدة أمين الأمة'),
    ('companions', '11192', 'الزبير حواري النبي ﷺ'),
    ('companions', '11191', 'طلحة والنبي ﷺ يوم أحد'),
    ('companions', '10548', 'عثمان تستحيي منه الملائكة'),
    ('companions', '11164', 'الحق على لسان عمر'),
]


def fetch(lang, hid):
    req = urllib.request.Request(API.format(lang=CODE.get(lang, lang), id=hid), headers={'User-Agent': 'masjid-nabawi-visitor-guide/1.0 (library build)', 'Accept': 'application/json'})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return None  # no translation in this language
            time.sleep(2 * (attempt + 1))
        except Exception:
            time.sleep(2 * (attempt + 1))
    raise SystemExit(f'failed: {lang} {hid}')


def main():
    jobs = [(lang, hid) for _, hid, _ in IDS for lang in LANGS]
    with ThreadPoolExecutor(8) as ex:
        res = dict(zip(jobs, ex.map(lambda j: fetch(*j), jobs)))
    out = {
        '_note': 'Generated by scripts/library-hadith-from-hadeethenc.py — do not edit by hand. Texts are HadeethEnc.com translations, unmodified.',
        'source': {'name': 'HadeethEnc.com — موسوعة الأحاديث النبوية', 'url': 'https://hadeethenc.com', 'terms': 'https://hadeethenc.com/ar/home (الشروط والسياسات)', 'fetched': date.today().isoformat()},
        'hadiths': [],
    }
    for section, hid, topic in IDS:
        ar = res[('ar', hid)]
        if not ar:
            raise SystemExit(f'missing Arabic: {hid}')
        h = {
            'id': hid,
            'section': section,
            'topic': topic,
            'url': f'https://hadeethenc.com/ar/browse/hadith/{hid}',
            'reference': ar.get('reference', ''),
            'attribution': ar.get('attribution', ''),
            'grade': ar.get('grade', ''),
            'review': 'draft',
            'available': ar.get('translations', []),
            'text': {},
        }
        for lang in LANGS:
            d = res[(lang, hid)]
            if not d:
                continue
            h['text'][lang] = {k: d[k] for k in ('title', 'hadeeth', 'explanation', 'hints', 'attribution', 'grade', 'words_meanings', 'reference') if k in d}
        out['hadiths'].append(h)
    open('data/library/hadith.json', 'w', encoding='utf-8').write(json.dumps(out, ensure_ascii=False, indent=1) + '\n')
    for h in out['hadiths']:
        print(h['id'], h['topic'], '|', h['grade'], '|', h['attribution'], '| languages:', len(h['text']))


if __name__ == '__main__':
    main()
